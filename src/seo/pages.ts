export const pageByPath = (path: string) => SEO_PAGES.find((p) => p.path === path)

export function normalizePath(path: string): string {
  if (!path || path === '/') return '/'
  return path.endsWith('/') ? path : `${path}/`
}

/** ลำดับจากหน้าแรกจนถึงหน้านี้ — ใช้ทั้งบนหน้าเว็บและใน JSON-LD */
export function breadcrumbs(page: SeoPage): { name: string; path: string }[] {
  if (page.path === '/') return []
  const chain = [{ name: 'หน้าแรก', path: '/' }]
  const parts = page.path.split('/').filter(Boolean)
  let current = '/'
  for (const part of parts) {
    current += `${part}/`
    const found = pageByPath(current)
    if (found) chain.push({ name: found.name, path: found.path })
  }
  return chain
}

const THAI_MONTHS = ['มกราคม', 'กุมภาพันธ์', 'มีนาคม', 'เมษายน', 'พฤษภาคม', 'มิถุนายน', 'กรกฎาคม', 'สิงหาคม', 'กันยายน', 'ตุลาคม', 'พฤศจิกายน', 'ธันวาคม']

/** เขียนเองแทน Intl เพื่อให้ผลตรงกันทุกที่ ทั้งตอนสร้าง HTML และตอน hydrate */
export function thaiDate(iso: string): string {
  const [y, m, d] = iso.split('-').map(Number)
  return `${d} ${THAI_MONTHS[m - 1]} ${y + 543}`
}
